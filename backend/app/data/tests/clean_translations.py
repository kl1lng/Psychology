def clean_dict(obj):
    if isinstance(obj, dict):
        if "ru" in obj and "kk" in obj:
            if isinstance(obj["kk"], str) and obj["kk"].startswith("[Қаз] "):
                obj["kk"] = obj["kk"].replace("[Қаз] ", "").strip()
            if isinstance(obj["kk"], str) and obj["kk"].startswith("[Қаз]"):
                obj["kk"] = obj["kk"].replace("[Қаз]", "").strip()
        for k, v in obj.items():
            clean_dict(v)
    elif isinstance(obj, list):
        for item in obj:
            clean_dict(item)

def process_eysenck():
    path = os.path.join(TESTS_DIR, "eysenck_epi_a.json")
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    clean_dict(data)

    for q in data.get("questions", []):
        qid = q["id"]
        if qid in EYSENCK_KK_QUESTIONS:
            q["text"]["kk"] = EYSENCK_KK_QUESTIONS[qid]

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("Eysenck cleaned and updated with Kazakh translations.")

